//! Optional per-task diagnostic recording. File limits never interrupt effects.
use std::{future::Future, path::Path};

use smallhead_core::diagnostics::{self, DiagnosticEvent};
use tokio::{fs::File, io::AsyncWriteExt, sync::mpsc};

const MAX_BYTES: usize = 32 * 1024 * 1024;

struct Journal {
    file: Option<File>,
    bytes: usize,
    omitted: usize,
}

impl Journal {
    async fn event(&mut self, event: &DiagnosticEvent) {
        let Ok(mut line) = serde_json::to_vec(event) else {
            return;
        };
        line.push(b'\n');
        if self.bytes.saturating_add(line.len()) > MAX_BYTES {
            self.omitted += 1;
            return;
        }
        if let Some(file) = self.file.as_mut() {
            if let Err(error) = file.write_all(&line).await {
                tracing::error!(%error, "A2A diagnostic write failed; task continues");
                self.file = None;
            } else {
                self.bytes += line.len();
            }
        }
    }
}

pub(crate) async fn record<T>(
    dir: &Path,
    task_id: &str,
    turn: impl Future<Output = Result<T, String>>,
) -> Result<T, String> {
    tokio::fs::create_dir_all(dir)
        .await
        .map_err(|e| e.to_string())?;
    // task_id is generated by the host, never taken from peer text.
    let file = File::create(dir.join(format!("{task_id}.jsonl")))
        .await
        .map_err(|e| e.to_string())?;
    let mut journal = Journal {
        file: Some(file),
        bytes: 0,
        omitted: 0,
    };
    let (sink, mut events) = mpsc::unbounded_channel();
    let mut turn = Box::pin(diagnostics::observe(sink, turn));
    let result = loop {
        tokio::select! {
            result = &mut turn => break result,
            Some(event) = events.recv() => journal.event(&event).await,
        }
    };
    drop(turn);
    while let Ok(event) = events.try_recv() {
        journal.event(&event).await;
    }
    if let Some(file) = journal.file.as_mut() {
        let footer = serde_json::json!({"layer":"a2a","event":"journal_end",
            "omitted_events":journal.omitted,"driver_error":result.as_ref().err()});
        if let Err(error) = file.write_all(format!("{footer}\n").as_bytes()).await {
            tracing::error!(%error, "A2A diagnostic footer write failed");
        }
        if let Err(error) = file.flush().await {
            tracing::error!(%error, "A2A diagnostic flush failed");
        }
    }
    result
}
